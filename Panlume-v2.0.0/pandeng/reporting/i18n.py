def localize_report_text(text: str, language: str) -> str:
    if language not in {"zh-TW", "ja"}:
        return text
    lines = []
    for line in text.splitlines():
        if line.strip().startswith(("原始告警：", "- ")):
            lines.append(line)
            continue
        localized = to_traditional(line) if language == "zh-TW" else line
        if language == "ja":
            for source, target in _JA_REPLACEMENTS.items():
                localized = localized.replace(source, target)
        lines.append(localized)
    return "\n".join(lines)
