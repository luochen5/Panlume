def to_traditional(text: str) -> str:
    return text.translate(_TRADITIONAL)


def normalize_language(value: Any) -> str:
    """只接受内置语言代码；调用方负责把 ValueError 转为设置错误。"""
    if value not in SUPPORTED_LANGUAGES:
        raise ValueError("language 只支持 zh-CN、zh-TW、en 或 ja。")
    return str(value)


def translate(text: str, language: str = DEFAULT_LANGUAGE) -> str:
    """按启动语言翻译；日语缺失时回退英文，非字符串原样返回。"""
    if not isinstance(text, str):
        return text
    if language == "en":
        return _EN.get(text, text)
    if language == "zh-TW":
        return to_traditional(text)
    if language == "ja":
        return _JA.get(text, _EN.get(text, text))
    return text


def translate_observation_message(text: str, language: str = DEFAULT_LANGUAGE) -> str:
    """只翻译观察运行器的固定提示；代码、来源和错误详情保持原样。"""
    if language == "zh-CN":
        return text
    translated = translate(text, language)
    if translated != text:
        return translated
    if language == "ja":
        patterns = (
            (r"第 (\d+) 轮观察中", r"第\1ラウンドを監視中"),
            (r"第 (\d+) 轮完成；等待下一轮", r"第\1ラウンド完了。次を待機中"),
            (r"第 (\d+) 轮完成：(\d+) 个代码有错误", r"第\1ラウンド完了。\2銘柄でエラー"),
            (r"第 (\d+) 轮完成", r"第\1ラウンド完了"),
        )
    else:
        patterns = (
            (r"第 (\d+) 轮观察中", r"Round \1 in progress"),
            (r"第 (\d+) 轮完成；等待下一轮", r"Round \1 completed; waiting for the next round"),
            (r"第 (\d+) 轮完成：(\d+) 个代码有错误", r"Round \1 completed: errors for \2 codes"),
            (r"第 (\d+) 轮完成", r"Round \1 completed"),
        )
    for pattern, replacement in patterns:
        if re.fullmatch(pattern, text):
            return re.sub(pattern, replacement, text)
    return text


def translate_widget_tree(widget: Any, language: str) -> None:
    """翻译 Tk 静态控件文字；历史 Text 内容和数据库记录不在此改写。"""
    if language == "zh-CN":
        return
    try:
        widget.configure(text=translate(widget.cget("text"), language))
    except Exception:
        pass
    if widget.winfo_class() == "TButton":
        try:
            widget.configure(text=translate(widget.cget("text"), language))
        except Exception:
            pass
    if widget.winfo_class() == "Treeview":
        try:
            for column in widget["columns"]:
                widget.heading(column, text=translate(widget.heading(column, "text"), language))
        except Exception:
            pass
    for child in widget.winfo_children():
        translate_widget_tree(child, language)
